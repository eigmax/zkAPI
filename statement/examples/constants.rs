//! Prints `statement/src/constants.rs`: the Poseidon parameters, the generators G, H and J and
//! the curve's d, as canonical limbs. `cargo run -p zkapi-ziren-statement --example constants`.

use ark_bn254::Fr;
use ark_ec::twisted_edwards::TECurveConfig;
use ark_ed_on_bn254::{EdwardsAffine, EdwardsConfig};
use zkapi_ziren_statement::fr::F;
use zkapi_ziren_statement::{derive_generator, derive_poseidon_config, BLINDING_LABEL, NOTE_LABEL};

fn limbs(value: &Fr) -> String {
    let limbs = F::from_ark(value).0.map(|limb| format!("{limb:#010x}"));
    format!("F([{}])", limbs.join(", "))
}

fn rows(name: &str, doc: &str, rows: &[Vec<Fr>]) {
    println!("/// {doc}");
    println!(
        "pub const {name}: [[F; {}]; {}] = [",
        rows[0].len(),
        rows.len()
    );
    for row in rows {
        println!(
            "    [{}],",
            row.iter().map(limbs).collect::<Vec<_>>().join(", ")
        );
    }
    println!("];");
}

fn point(name: &str, doc: &str, point: &EdwardsAffine) {
    println!();
    println!("/// {doc}");
    println!("pub const {name}: Affine = Affine {{");
    println!("    x: {},", limbs(&point.x));
    println!("    y: {},", limbs(&point.y));
    println!("}};");
}

fn main() {
    let config = derive_poseidon_config();
    println!("//! Generated by `cargo run -p zkapi-ziren-statement --example constants`; the tests check");
    println!("//! each value against its derivation (Poseidon, `H`, `J`) or arkworks (`d`, `G`). Do not edit.");
    println!();
    println!("use crate::curve::Affine;");
    println!("use crate::fr::F;");
    println!();
    rows(
        "POSEIDON_ARK",
        "Poseidon round constants, `ark[round][lane]`.",
        &config.ark,
    );
    println!();
    rows("POSEIDON_MDS", "Poseidon MDS matrix.", &config.mds);
    point(
        "GENERATOR",
        "The Baby-JubJub generator `G` (arkworks' `EdwardsConfig::GENERATOR`).",
        &EdwardsConfig::GENERATOR,
    );
    point(
        "BLINDING_GENERATOR",
        "The blinding generator `H`.",
        &derive_generator(BLINDING_LABEL),
    );
    point(
        "NOTE_GENERATOR",
        "The note-binding generator `J`.",
        &derive_generator(NOTE_LABEL),
    );
    println!();
    println!("/// The curve's `d` (arkworks' `EdwardsConfig::COEFF_D`).");
    println!(
        "pub const EDWARDS_D: F = {};",
        limbs(&EdwardsConfig::COEFF_D)
    );
}
